const DICTIONARIES: Record<Language, Dictionary> = {
  'zh-CN': ZH,
  'en-US': EN,
}

export function translate(
  language: Language,
  key: string,
  values?: Record<string, string | number>,
): string {
  let text = DICTIONARIES[language][key] ?? DICTIONARIES['zh-CN'][key] ?? key
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

export function toolTitle(id: ToolId, language: Language): string {
  return translate(language, `tool.${id}.title`)
}

export function toolDescription(id: ToolId, language: Language): string {
  return translate(language, `tool.${id}.desc`)
}
