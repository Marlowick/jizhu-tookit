import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const chrome = process.env.JIZHU_CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const browser = await chromium.launch({ executablePath: chrome, headless: true, args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 1024 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))

try {
  await page.goto('http://127.0.0.1:1420/', { waitUntil: 'networkidle' })
  await page.waitForTimeout(300)

  assert.equal(await page.locator('.app').evaluate((node) => getComputedStyle(node).backgroundColor), 'rgb(238, 240, 243)')
  assert.equal(Math.round(await page.locator('.titlebar').evaluate((node) => node.getBoundingClientRect().height)), 40)
  assert.equal(Math.round(await page.locator('.statusbar').evaluate((node) => node.getBoundingClientRect().height)), 28)
  assert.equal(await page.locator('.titlebar-command').count(), 1)
  assert.equal(await page.locator('.titlebar-settings').count(), 1)
  assert.equal(await page.locator('.tiling-tab .tab-mode-icon').count(), 1)
  assert.equal(await page.locator('.empty-editor-guide').count(), 1)

  await page.locator('.titlebar-command').click()
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.palette').count(), 1)
  assert.equal(await page.locator('.palette-quick').count(), 0)
  assert.equal(await page.locator('.palette-search input').count(), 1)
  assert.equal(Math.round(await page.locator('.palette').evaluate((node) => node.getBoundingClientRect().width)), 640)
  assert.equal(Math.round(await page.locator('.palette').evaluate((node) => node.getBoundingClientRect().top)), 120)
  assert.equal(await page.locator('.palette').evaluate((node) => getComputedStyle(node).borderRadius), '10px')
  assert.equal(Math.round(await page.locator('.palette-search').evaluate((node) => node.getBoundingClientRect().height)), 46)
  assert.equal(Math.round(await page.locator('.palette-item').first().evaluate((node) => node.getBoundingClientRect().height)), 38)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Meta+k')
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.palette').count(), 1)
  assert.equal(await page.locator('.palette-search input').count(), 1)
  await page.keyboard.press('Escape')

  await page.keyboard.press('Meta+Shift+P')
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.palette-quick').count(), 1)
  assert.equal(await page.locator('.palette-search').count(), 0)
  assert.equal(await page.locator('.quick-command-header').innerText(), '快捷命令\nEsc 取消')
  assert.equal(Math.round(await page.locator('.palette-quick').evaluate((node) => node.getBoundingClientRect().width)), 460)
  assert.equal(Math.round(await page.locator('.palette-quick').evaluate((node) => node.getBoundingClientRect().right)), 1392)
  assert.equal(Math.round(await page.locator('.palette-quick').evaluate((node) => node.getBoundingClientRect().bottom)), 976)
  assert.equal(await page.locator('.quick-command-grid').evaluate((node) => getComputedStyle(node).gridTemplateColumns.split(' ').length), 2)
  await page.keyboard.press('/')
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.palette-quick').count(), 0)
  assert.equal(await page.locator('.palette-search input').count(), 1)
  await page.keyboard.press('Escape')

  await page.locator('.titlebar-settings').click()
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.settings-dialog').count(), 1)
  await page.locator('.settings-dialog').getByRole('button', { name: '关闭', exact: true }).click()

  await page.locator('.cm-content').click()
  await page.keyboard.type('hello')
  await page.waitForTimeout(150)
  assert.equal(await page.locator('.tiling-tab.active .tab-dirty-dot').count(), 1)
  assert.equal(await page.locator('.empty-editor-guide').count(), 0)
  assert.match(await page.locator('.statusbar').innerText(), /5 字符/)

  await page.keyboard.press('Meta+k')
  await page.keyboard.press('/')
  await page.locator('.palette-search input').fill('Mermaid 预览')
  await page.locator('.palette-item').first().click()
  await page.waitForTimeout(300)
  assert.equal(Math.round(await page.locator('.side-tool-shell-head').evaluate((node) => node.getBoundingClientRect().height)), 40)
  assert.equal(await page.locator('.side-tool-shell-head .side-tool-header-icon').count(), 1)
  assert.equal(await page.locator('.side-tool-source-badge').innerText(), '输入：当前文档')
  assert.equal(Math.round(await page.locator('.workspace-qr-editor').evaluate((node) => node.getBoundingClientRect().width)), 792)
  assert.equal(Math.round(await page.locator('.mermaid-toolbar').evaluate((node) => node.getBoundingClientRect().height)), 38)
  assert.equal(await page.locator('.mermaid-stage').evaluate((node) => getComputedStyle(node).backgroundColor), 'rgb(242, 244, 247)')

  await page.locator('.cm-content').click()
  await page.keyboard.press('Meta+a')
  await page.keyboard.insertText('flowchart LR\n  A[编辑] --> B[预览]')
  await page.waitForTimeout(900)
  assert.equal(await page.locator('.mermaid-canvas svg').count(), 1)
  await page.locator('.mermaid-toolbar .btn').filter({ hasText: '复制 SVG' }).click()
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.toast').count(), 1)
  const toastBox = await page.locator('.toast').boundingBox()
  assert.ok(toastBox)
  assert.equal(Math.round(toastBox.height), 36)
  assert.equal(Math.round(toastBox.x + toastBox.width), 1424)
  assert.equal(await page.locator('.toast').evaluate((node) => getComputedStyle(node).backgroundColor), 'rgb(250, 251, 252)')
  await page.getByRole('button', { name: '关闭Mermaid 预览', exact: true }).click()

  await page.keyboard.press('Meta+k')
  await page.keyboard.press('/')
  await page.locator('.palette-search input').fill('二维码')
  await page.locator('.palette-item').first().click()
  await page.waitForTimeout(400)
  assert.equal(Math.round(await page.locator('.qr-preview-only-head').evaluate((node) => node.getBoundingClientRect().height)), 40)
  assert.equal(await page.locator('.qr-preview-only-head .side-tool-source-badge').innerText(), '输入：当前文档')
  assert.equal(await page.locator('.qr-canvas').count(), 1)
  await page.getByRole('button', { name: '关闭二维码预览', exact: true }).click()

  assert.deepEqual(errors, [])
  console.log('Design UI checks passed')
} finally {
  await browser.close()
}
